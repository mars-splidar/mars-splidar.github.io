#!/usr/bin/env python3
"""Demo 2 — the count-distribution graphic on `/` (stage 09).

    python tools/build_demo_count.py            # write the SVG, splice it, check
    python tools/build_demo_count.py --check    # change nothing; fail on drift

Needs the Dead_time conda env (numpy + scipy, for the repo's own
`discretized_gaussian`). Run from anywhere; paths are resolved from this file.

WHAT IT DRAWS. One operating point, one panel: the sequential gold standard's
count histogram as bars, and the renewal, Zhang et al. (ICIP 2025) and MaRS
predicted count distributions as lines, each directly labelled at its curve.
Poisson's predicted mean is far off the axis at this flux, so it is an
off-scale marker at the right edge ("Poisson →"), never a stretched axis.

WHERE THE NUMBERS COME FROM. Nothing is copied into the site. Every array is
read through `video/data.py::count_distributions()`, which loads the repo's
stored results in `code/CVPR2026/` (`gt_hist_*`, `gt_stats_*`, `pred_stats_*`,
all `bin214_iter1e4_N1e3`) and builds each model's PMF with the repo's own
`utils.discretized_gaussian`. Its `icip` key IS Zhang et al., ICIP 2025.

THE OPERATING POINT. data.py's default, (S, B, t_d) = (8.2, 8.2, 75 ns), grid
index (8, 8, 5). Stage 09 scanned every stored t_d = 75 ns point: renewal's
mean is 7–546 sd off at all of them and MaRS's variance ratio 0.96–1.03, so
the contrast that decides the point is Zhang et al.'s spread. At (8.2, 8.2)
Zhang et al.'s variance is 0.30x the gold standard's — clearly too narrow —
while its centre is right, and renewal sits about 14 sd to the right, close
enough to share one axis with the histogram. That is the three-way contrast
the doc asks for, so the default stands.

THE RULES IT ENFORCES (stage 09 doc, T2):
  * no number inside the graphic — no tick values, no KL. Fig. 5's
    per-point KLs must never sit beside the grid-averaged 30x (stage 06 2c).
    Asserted on every <text> node and on the aria-label.
  * axis titles "Registered photon count" and "Probability" only.
  * colours from the site tokens, as `var(--token, #fallback)` so the inline
    copy follows mars.css and the standalone file still renders.
  * lines >= 2 px at any displayed size (non-scaling strokes, 2.5 px).
  * all text 21 user units in a 560-unit-wide viewBox, displayed at most
    560 CSS px wide: >= 12.8 CSS px at a 343 px figure (341 px of SVG).

PROVENANCE (printed; exit non-zero on any mismatch):
  * (S, B, t_d), grid index, the realization count (proven from the data:
    hist_gt x 10 000 is integer-valued and sums to 10 000),
  * each model's (mean, var) from count_distributions(), beside the mean and
    var of the very PMF arrays that are plotted. A PMF discretized to
    integers has variance ~ sigma^2 + 1/12, so variances are compared with
    that correction and a tolerance, and the deltas are printed;
  * the gold histogram's mean/var against the stored empirical statistics;
  * Poisson's mean is beyond the right edge of the axis;
  * --check: the committed assets/img/demo_count.svg and the copy inlined in
    index.html both equal what this script generates now.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True       # never leave .pyc files in video/ or code/

REPO = Path(__file__).resolve().parent.parent
VIDEO = Path(os.environ.get("MARS_VIDEO_DIR",
                            REPO.parent.parent / "video")).resolve()
SVG_OUT = REPO / "assets" / "img" / "demo_count.svg"
PAGE = REPO / "index.html"
START = "<!-- demo_count:start (generated by tools/build_demo_count.py; do not edit by hand) -->"
END = "<!-- demo_count:end -->"

# ---- geometry (user units) ------------------------------------------------
W, H = 560, 340
PL, PR, PT, PB = 46, 12, 44, 52         # plot margins
X0, X1 = 1140, 1275                     # count axis; renewal fits, Poisson does not
FS = 21                                 # every text node
STROKE = 2.5                            # CSS px, non-scaling

COL = {
    "gold":    "var(--grey, #5A5A5A)",
    "renewal": "var(--red, #B03A2E)",
    "icip":    "var(--blue, #2E6DA4)",
    "ours":    "var(--green, #0E7A46)",
    "poisson": "var(--red, #B03A2E)",
    "axis":    "var(--grey, #5A5A5A)",
    "text":    "var(--dark, #1F1F1F)",
}
FONT = "var(--font-body, Inter, 'Helvetica Neue', Arial, sans-serif)"

ARIA = ("Count distribution at one high-flux operating point. Bars: the "
        "sequential gold standard's histogram. The renewal model's "
        "distribution sits far to the right of it; Zhang et al.'s is centred "
        "on it but much too narrow; MaRS matches both its centre and its "
        "width. Poisson's prediction lies far off the chart to the right.")

FAIL: list[str] = []


def chk(ok: bool, what: str) -> str:
    if not ok:
        FAIL.append(what)
    return "OK" if ok else "** MISMATCH **"


def load():
    sys.path.insert(0, str(VIDEO))
    import numpy as np  # noqa: F401
    import data  # video/data.py
    return data.count_distributions()


def moments(ks, p):
    import numpy as np
    ks, p = np.asarray(ks, float), np.asarray(p, float)
    p = p / p.sum()
    m = float((ks * p).sum())
    return m, float(((ks - m) ** 2 * p).sum())


def build_svg(d) -> str:
    import numpy as np

    pw, ph = W - PL - PR, H - PT - PB
    ymax = 1.12 * max(float(np.max(d[k][1])) for k in ("renewal", "icip", "ours"))

    def X(k):
        return PL + (k - X0) / (X1 - X0) * pw

    def Y(p):
        return PT + ph - p / ymax * ph

    f = lambda v: f"{v:.1f}"
    out = []
    a = out.append
    a(f'<svg class="mars-count" xmlns="http://www.w3.org/2000/svg" '
      f'viewBox="0 0 {W} {H}" role="img" aria-label="{ARIA}" '
      f'font-family="Inter, Helvetica Neue, Arial, sans-serif" '
      f'style="font-family: {FONT}">')

    # gold-standard histogram — one bar per integer count
    bw = 0.8 * pw / (X1 - X0)
    a(f'  <g style="fill: {COL["gold"]}" fill-opacity="0.34">')
    for k, p in zip(d["bin_centers"], d["hist_gt"]):
        if p <= 0:
            continue
        a(f'    <rect x="{f(X(k) - bw / 2)}" y="{f(Y(p))}" width="{f(bw)}" '
          f'height="{f(Y(0) - Y(p))}"/>')
    a('  </g>')

    # axes: lines only — no ticks, no tick values (no numbers in the graphic)
    a(f'  <g style="stroke: {COL["axis"]}" stroke-width="1.5" fill="none" '
      f'vector-effect="non-scaling-stroke">')
    a(f'    <path vector-effect="non-scaling-stroke" d="M{PL} {PT - 6}V{f(Y(0))}H{W - PR}"/>')
    a('  </g>')

    # model curves, PMF over integer counts
    for key in ("renewal", "icip", "ours"):
        ks, pmf = d[key]
        pts = " ".join(f"{f(X(k))},{f(Y(p))}" for k, p in zip(ks, pmf))
        a(f'  <polyline class="mars-count__{key}" points="{pts}" fill="none" '
          f'style="stroke: {COL[key]}" stroke-width="{STROKE}" '
          f'stroke-linejoin="round" vector-effect="non-scaling-stroke"/>')

    def peak(key):
        ks, pmf = d[key]
        i = int(np.argmax(pmf))
        return float(ks[i]), float(pmf[i])

    def text(x, y, s, col, anchor="middle", weight=600, extra=""):
        a(f'  <text x="{f(x)}" y="{f(y)}" text-anchor="{anchor}" '
          f'font-size="{FS}" font-weight="{weight}" style="fill: {col}"{extra}>{s}</text>')

    # direct labels at the curves
    kr, pr = peak("renewal")
    text(X(kr), Y(pr) - 10, "Renewal", COL["renewal"])
    ki, pi = peak("icip")
    text(X(ki), Y(pi) - 10, "Zhang et al.", COL["icip"])

    # MaRS: left flank, with a short leader to its curve
    m, v = d["ours_mv"]
    kx = m - 1.25 * np.sqrt(v)
    ks, pmf = d["ours"]
    py = float(np.interp(kx, ks, pmf))
    lx, ly = X(kx) - 34, Y(py) - 26
    a(f'  <path d="M{f(lx + 4)} {f(ly + 4)}L{f(X(kx) - 3)} {f(Y(py) - 2)}" '
      f'style="stroke: {COL["ours"]}" stroke-width="1.5" fill="none" '
      f'vector-effect="non-scaling-stroke"/>')
    text(lx, ly, "MaRS", COL["ours"], anchor="end", weight=700)

    # gold standard: right flank of the bars
    gm, gv = d["emp_mean"], d["emp_var"]
    gx = gm + 1.6 * np.sqrt(gv)
    gy = float(np.interp(gx, d["bin_centers"], d["hist_gt"]))
    tx, ty = X(gx) + 30, Y(gy) - 18
    a(f'  <path d="M{f(tx - 4)} {f(ty - 6)}L{f(X(gx) + 3)} {f(Y(gy) - 2)}" '
      f'style="stroke: {COL["axis"]}" stroke-width="1.5" fill="none" '
      f'vector-effect="non-scaling-stroke"/>')
    text(tx, ty, "Gold standard", COL["text"], anchor="start")

    # Poisson: an off-scale marker at the right edge, never a stretched axis
    text(W - PR, Y(0) - 12, "Poisson →", COL["poisson"], anchor="end")

    # axis titles
    text(PL + pw / 2, H - 14, "Registered photon count", COL["axis"], weight=500)
    text(0, 0, "Probability", COL["axis"], weight=500,
         extra=f' transform="translate({PL - 16} {f(PT + ph / 2)}) rotate(-90)"')
    a('</svg>')
    return "\n".join(out) + "\n"


def provenance(d, svg: str) -> None:
    import numpy as np
    print("Demo 2 — count-distribution graphic, provenance  (stage 09)")
    print("  source: video/data.py::count_distributions()  "
          "(code/CVPR2026/{gt_hist,gt_stats,pred_stats}_bin214_iter1e4_N1e3.npz)")
    print(f"  operating point  S = {d['S']}, B = {d['B']}, t_d = {d['td']} ns   "
          f"(grid index (8, 8, 5), data.py's default)")
    print("    " + chk((d["S"], d["B"], d["td"]) == (8.2, 8.2, 75.0),
                       "operating point") + "  matches the caption's S = B = 8.2, t_d = 75 ns")

    h = np.asarray(d["hist_gt"], float)
    n = h * 1e4
    integer = bool(np.allclose(n, np.round(n), atol=1e-6))
    print(f"  realizations     hist_gt x 10 000 integer-valued: {integer}; "
          f"sum = {n.sum():.6f}")
    print("    " + chk(integer and abs(n.sum() - 1e4) < 1e-6,
                       "realization count") + "  10 000 sequential gold-standard realizations")

    gm, gv = moments(d["bin_centers"], h)
    print(f"\n  {'model':<16}{'stored mean':>13}{'stored var':>12}"
          f"{'plotted mean':>14}{'plotted var':>13}{'d mean':>9}{'d var*':>9}")
    print(f"  {'gold standard':<16}{d['emp_mean']:>13.4f}{d['emp_var']:>12.4f}"
          f"{gm:>14.4f}{gv:>13.4f}{gm - d['emp_mean']:>9.4f}{gv - d['emp_var']:>9.4f}  "
          + chk(abs(gm - d["emp_mean"]) < 0.05 and abs(gv - d["emp_var"]) < 0.25,
                "gold moments"))
    names = {"renewal": "renewal", "icip": "Zhang et al.", "ours": "MaRS"}
    for key, name in names.items():
        m, v = d[key + "_mv"]
        pm, pv = moments(*d[key])
        dv = pv - (v + 1 / 12)
        print(f"  {name:<16}{m:>13.4f}{v:>12.4f}{pm:>14.4f}{pv:>13.4f}"
              f"{pm - m:>9.4f}{dv:>9.4f}  "
              + chk(abs(pm - m) < 0.02 and abs(dv) < 0.05, name + " moments"))
    pm_, pv_ = d["poisson_mv"]
    print(f"  {'Poisson':<16}{pm_:>13.4f}{pv_:>12.4f}{'(not plotted: off-scale marker)':>36}")
    print("    " + chk(pm_ > X1, "Poisson off-scale")
          + f"  Poisson mean {pm_:.0f} > right edge of the axis {X1}")
    print("  * d var = plotted var - (stored var + 1/12): integer discretization")

    texts = re.findall(r"<text[^>]*>([^<]*)</text>", svg)
    aria = re.search(r'aria-label="([^"]*)"', svg).group(1)
    digits = [t for t in texts + [aria] if re.search(r"[0-9]", t)]
    print(f"\n  text nodes: {texts}")
    print("  " + chk(not digits, "numbers in graphic")
          + f"  no digit in any <text> or in the aria-label ({len(texts)} text nodes)")
    req = {"Registered photon count", "Probability"}
    print("  " + chk(req <= set(texts), "axis titles")
          + "  axis titles exactly 'Registered photon count' and 'Probability'")
    print("  " + chk(not re.search(r"<title|<desc", svg), "no title/desc")
          + "  no <title>/<desc>: the finding is the aria-label")


def splice(page: str, svg: str) -> str:
    i, j = page.index(START), page.index(END)
    indent = re.search(r"([ \t]*)" + re.escape(START), page).group(1)
    body = "".join(indent + ln + "\n" if ln else "\n" for ln in svg.rstrip("\n").split("\n"))
    return page[:i + len(START)] + "\n" + body + indent + page[j:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="write nothing; fail if the SVG file or the inline copy drifted")
    args = ap.parse_args()

    d = load()
    svg = build_svg(d)
    provenance(d, svg)

    page = PAGE.read_text(encoding="utf-8")
    if START not in page or END not in page:
        FAIL.append("splice markers")
        print("\n  ** index.html has no demo_count markers")
    else:
        new_page = splice(page, svg)
        if args.check:
            file_ok = SVG_OUT.exists() and SVG_OUT.read_text(encoding="utf-8") == svg
            print("\n  " + chk(file_ok, "svg file drift")
                  + f"  {SVG_OUT.relative_to(REPO)} equals a fresh build")
            print("  " + chk(new_page == page, "inline drift")
                  + "  the copy inlined in index.html equals a fresh build")
        else:
            SVG_OUT.write_text(svg, encoding="utf-8")
            PAGE.write_text(new_page, encoding="utf-8")
            print(f"\n  wrote {SVG_OUT.relative_to(REPO)} ({len(svg.encode())} B) "
                  f"and spliced it into index.html")

    print(f"\n{'FAIL — ' + ', '.join(FAIL) if FAIL else 'PASS'}")
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
